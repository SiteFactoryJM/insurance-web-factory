import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entries = await readdir(path.join(root, "sites"), { withFileTypes: true });
const domains = [];
for (const entry of entries) {
  if (!entry.isDirectory() || entry.name.startsWith("_")) continue;
  const site = JSON.parse(await readFile(path.join(root, "sites", entry.name, "site.json"), "utf8"));
  if (site.status !== "published" || site.demo?.enabled) continue;
  for (const domain of site.domains ?? []) {
    const host = String(domain).trim().toLowerCase().replace(/^https?:\/\//, "").replace(/\/.*$/, "");
    if (host) domains.push({ pattern: host, custom_domain: true });
  }
}
const config = {
  name: "insurance-web-factory",
  main: "src/index.ts",
  compatibility_date: "2026-08-31",
  workers_dev: true,
  assets: { directory: "./public", binding: "ASSETS", run_worker_first: true },
  routes: domains,
  vars: { DEMO_SITE_ID: "demo-agent" },
};
const content = `// Generated by npm run domains:generate\n${JSON.stringify(config, null, 2)}\n`;
await writeFile(path.join(root, "wrangler.domains.jsonc"), content, "utf8");
console.log(`Generated wrangler.domains.jsonc with ${domains.length} custom domain(s)`);
