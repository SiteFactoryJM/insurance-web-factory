import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { collectProductionDomains, loadSites, repositoryRoot } from "./production-sites.mjs";

export function buildProductionWranglerConfig(sites) {
  const { routes } = collectProductionDomains(sites, { requireTargets: false });
  return {
    name: "insurance-web-factory",
    main: "src/index.ts",
    compatibility_date: "2026-08-31",
    workers_dev: false,
    assets: { directory: "./public", binding: "ASSETS", run_worker_first: true },
    routes: routes.map(({ host }) => ({ pattern: host, custom_domain: true })),
    vars: { DEMO_SITE_ID: "demo-agent" },
  };
}

async function main() {
  const sites = await loadSites(repositoryRoot);
  const config = buildProductionWranglerConfig(sites);
  const outputPath = path.join(repositoryRoot, "wrangler.domains.jsonc");
  const content = `// Generated by npm run domains:generate\n${JSON.stringify(config, null, 2)}\n`;
  await writeFile(outputPath, content, "utf8");
  console.log(`Generated wrangler.domains.jsonc with ${config.routes.length} production custom domain(s); workers_dev=false`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
